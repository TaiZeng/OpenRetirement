// Builds src/data/historicalReturns.ts from the Goyal-Welch annual dataset.
// Source: Amit Goyal and Ivo Welch, "A Comprehensive Look at the Empirical Performance
// of Equity Premium Prediction" (RFS 2008), data maintained at
// https://www.ivo-welch.org/professional/goyal-welch/ (goyal-welch-a.csv).
//
// The data is not redistributed in this repository. This script downloads it on each machine,
// checks it against a pinned SHA-256 so golden tests stay reproducible, and writes a local,
// git-ignored module. It runs automatically before `npm run dev`, `npm test`, and `npm run build`.
// Pass --force to re-download.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const URL = 'https://www.ivo-welch.org/professional/goyal-welch/goyal-welch-a.csv';
const CACHE = '.cache/goyal-welch-a.csv';
const OUT = 'src/data/historicalReturns.ts';
// SHA-256 of the file the Trinity golden tests were validated against.
const EXPECTED_SHA256 = '119bbc9acedb991d7a1f246f7c9eab996632465ab3851560cd5ed7806f51db9e';
const force = process.argv.includes('--force');

if (existsSync(OUT) && !force) process.exit(0);

if (!existsSync(CACHE) || force) {
  mkdirSync('.cache', { recursive: true });
  console.log(`Downloading historical returns from ${URL}`);
  let res;
  try {
    res = await fetch(URL);
  } catch (e) {
    console.error(`Could not download historical returns (${e.message}). Check your connection and rerun \`npm run data:returns\`.`);
    process.exit(1);
  }
  if (!res.ok) {
    console.error(`Download failed: HTTP ${res.status} from ${URL}`);
    process.exit(1);
  }
  writeFileSync(CACHE, Buffer.from(await res.arrayBuffer()));
}

const raw = readFileSync(CACHE);
const sha = createHash('sha256').update(raw).digest('hex');
if (sha !== EXPECTED_SHA256) {
  console.error(
    `Historical returns file changed upstream.\n  expected ${EXPECTED_SHA256}\n  got      ${sha}\n` +
      'Review the new data, rerun the golden tests, then update EXPECTED_SHA256 in scripts/build-returns.mjs.',
  );
  process.exit(1);
}

const [header, ...lines] = raw.toString('utf8').trim().split(/\r?\n/);
const cols = header.split(',');
const col = (name) => {
  const i = cols.indexOf(name);
  if (i < 0) throw new Error(`missing column ${name}`);
  return i;
};
const [iy, is, ib, ic, ii] = ['yyyy', 'vwm', 'corprate', 'tbill', 'infl'].map(col);

const rows = [];
for (const line of lines) {
  const f = line.split(',');
  const year = Number(f[iy]);
  const vals = [f[is], f[ib], f[ic], f[ii]];
  if (vals.some((v) => v === '' || Number.isNaN(Number(v)))) continue;
  // Source values are percents. Store fractions rounded to 6 decimals.
  const [s, b, c, i] = vals.map((v) => Math.round(Number(v) * 1e4) / 1e6);
  rows.push(`  [${year}, ${s}, ${b}, ${c}, ${i}],`);
}

mkdirSync('src/data', { recursive: true });
writeFileSync(
  OUT,
  `// GENERATED by scripts/build-returns.mjs. Not committed. Do not edit by hand.
// Annual nominal total returns and CPI inflation, as fractions.
// stocks: CRSP value-weighted market incl. dividends (vwm)
// bonds: long-term high-grade corporate bond total return (corprate, Ibbotson series)
// cash: 3-month Treasury bill yield (tbill)
// inflation: CPI (infl)
// Source: Goyal & Welch (2008), https://www.ivo-welch.org/professional/goyal-welch/
export const HISTORICAL_RETURNS: ReadonlyArray<readonly [year: number, stocks: number, bonds: number, cash: number, inflation: number]> = [
${rows.join('\n')}
];
`,
);
console.log(`Wrote ${rows.length} years of historical returns to ${OUT}`);
